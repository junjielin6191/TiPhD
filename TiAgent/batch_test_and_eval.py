def evaluate_blind(query, model_response):
    """让 glm-5 进行盲评"""
    try:
        res = bx_client.chat.completions.create(
            model="glm-5",
            messages=[
                {"role": "system", "content": SYSTEM_PROMPT},
                {"role": "user", "content": f"User Query: {query}\n\nModel Response to Evaluate:\n{model_response}"}
            ],
            response_format={"type": "json_object"},
            temperature=0.0
        )
        data = json.loads(res.choices[0].message.content)
        # 计算加权总分
        total = (data['logic'] * 0.4) + (data['tools'] * 0.3) + (data['feasibility'] * 0.3)
        data['total_score'] = round(total, 2)
        return data
    except Exception as e:
        print(f"Evaluation error: {e}")
        return None

